//===============================================================================
//********************************程序主函数*************************************
//主循环每1ms翻转一次IOB1
//===============================================================================
void main(void)					  		//程序主函数
{
	SYSTEM_INIT();                  		//系统初始化
	TC1_INIT();				   	  		    //TC1初始化
	while(1) 
	{
		CLRWDT();					  		//清除看门狗
		TC1_Work();	
	}
}

