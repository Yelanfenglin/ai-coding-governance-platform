//用户不可更改
#include "COMMON.H"
//===============================================================================
//*********************************TC1处理程序***********************************
//TC1处理:主循环TC1中断标志置1,每1ms翻转一次IOC1口
//===============================================================================
void TC1_Work(void)
{
	if(b_TC1_Flag == 1)
	{
		b_TC1_Flag = 0;	
		IOC1 = ~IOC1;
	}
}

//===============================================================================
//******************************TC1中断处理函数**********************************
//定时器TC1每计数1ms，进一次中断，标志位置高
//===============================================================================
void TC1_Interrupt (void)				
{
	if(TC1IF)
	{					
		TC1IF = 0;
		b_TC1_Flag = 1;
	}
}
//===============================================================================
//*********************************TC1初始化*************************************
//TC1设置：16位模式，高频系统时钟，1:16分频
//t =计数/（时钟/分频）     1ms = （999+1）/（32/32）
//开启TC1溢出中断和总中断
//===============================================================================
void TC1_INIT(void)
{
//1、TC1设置
    T1CR =0x0D; 			
    TC1CH = 0;				
    TC1CL = 0;				
	TC1PRL = 0xE7;
	TC1PRH = 0x03;
	TC1EN = 1;	
//2、高优先级中断设置 
	TC1IE = 1;
	TC1IF = 0;	
	TC1IP = 0;
	GIEH = 1;				
}
